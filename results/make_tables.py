"""Build results/tables/*.md from experiments/runs.jsonl. Never edit the tables by hand.

    .venv/bin/python results/make_tables.py --write
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

RUNS = Path("experiments/runs.jsonl")
OUT = Path("results/tables")
MEASURES = ["top", "margin", "lead_vs_mean", "concentration"]


def latest_runs() -> list[dict]:
    runs = {}
    for r in map(json.loads, RUNS.open()):
        runs[r["exp"]] = r
    return list(runs.values())


def pct(x: float) -> str:
    return f"{100 * x:.1f}"


def main_table(runs: list[dict]) -> str:
    lines = ["# Main results", "", "Generated by `results/make_tables.py` from `experiments/runs.jsonl`.", "",
             "| exp | pages | model | data | labels checked | group | n | accuracy % | NLL | Brier | ECE (top p) |",
             "|---|---|---|---|---|---|---|---|---|---|---|"]
    for r in runs:
        for g, m in r["metrics"]["groups"].items():
            lines.append(f"| `{r['exp']}` | {r['pages']} | {r['config']['model']} | {r['data']['name']} | {r['data']['labels_checked']} "
                         f"| {g} | {m['n']} | {pct(m['accuracy'])} | {m['nll']:.3f} | {m['brier']:.3f} | {m['ece']:.3f} |")
    lines += ["", "## Coverage at fixed error, per confidence measure", "",
              "Which measure DocJev uses is undecided (JOURNAL entry 6). Thresholds are chosen on the same data "
              "(oracle), so these coverages are optimistic.", "",
              "| exp | group | measure | coverage @≤1% error | coverage @≤5% error | AURC |", "|---|---|---|---|---|---|"]
    for r in runs:
        for g, m in r["metrics"]["groups"].items():
            for name in MEASURES:
                b = m["by_measure"][name]
                lines.append(f"| `{r['exp']}` | {g} | {name} | {pct(b['cov@0.01'])} | {pct(b['cov@0.05'])} | {b['aurc']:.3f} |")
    return "\n".join(lines) + "\n"


def detail_table(runs: list[dict]) -> str:
    lines = ["# Per-run detail", "", "Generated by `results/make_tables.py`.", ""]
    for r in runs:
        m = r["metrics"]
        lines += [f"## `{r['exp']}`", "",
                  f"Scored {m['scored']}/{m['items']} questions; latency p50 {m['latency_s']['p50']:.2f} s, "
                  f"p95 {m['latency_s']['p95']:.2f} s, max {m['latency_s']['max']:.2f} s; "
                  f"{m['input_tokens']['total']:,} input tokens "
                  f"(median {m['input_tokens']['per_request_median']:.0f} per request).", "",
                  f"Hosted `confidence` vs normalised concentration, max abs difference: "
                  f"{m['hosted_confidence_vs_concentration_max_abs_diff']}", "",
                  "### Choice accuracy by true type", "", "| type | accuracy % |", "|---|---|"]
        lines += [f"| {k} | {pct(v)} |" for k, v in m["choice_accuracy_by_class"].items()]
        lines += ["", "### Most common choice confusions", "", "| true type | predicted | pages |", "|---|---|---|"]
        lines += [f"| {c['gold']} | {c['pred']} | {c['n']} |" for c in m["choice_confusions"]]
        a = m["choice_vs_noul_true"]
        lines += ["", "### Choice vs yes/no about the true type, per page", "",
                  "| both right | choice only | yes/no only | both wrong |", "|---|---|---|---|",
                  f"| {a['both_right']} | {a['choice_only']} | {a['noul_only']} | {a['both_wrong']} |", ""]
    return "\n".join(lines)


if __name__ == "__main__":
    ap = argparse.ArgumentParser()
    ap.add_argument("--write", action="store_true")
    args = ap.parse_args()
    runs = latest_runs()
    tables = {"main.md": main_table(runs), "detail.md": detail_table(runs)}
    for name, text in tables.items():
        if args.write:
            OUT.mkdir(parents=True, exist_ok=True)
            (OUT / name).write_text(text)
        else:
            print(text)
